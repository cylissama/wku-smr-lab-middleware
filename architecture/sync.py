"""Generate the architecture model's inventory from the deploy files.

Reads docker-compose.yml (AMS services) and deploy/swarm-edge-nodes.yml (edge
services, hostnames and device ids resolved from deploy/.env.example) and
writes web/architecture/generated/. Each service's smr.description label
becomes its description. Run from anywhere after changing a service:

    python architecture/sync.py

tests/architecture_test.py fails while the generated files are out of date.
Everything else (relationships, children, links) is hand-written in
web/architecture/model/, which `extend`s these elements.
"""
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "architecture" / "generated"
REPO_URL = "https://github.com/cylissama/wku-smr-lab-middleware/blob/main"
HEADER = (
    "// GENERATED by architecture/sync.py from {source}. Do not edit:\n"
    "// change the smr.description label there and rerun `python architecture/sync.py`.\n"
)

# Element kind per compose service (spec.c4); anything else is a plain `service`
KINDS = {"mqtt-broker": "broker", "web": "webapp", "pgadmin": "webapp", "postgres": "database"}
# Logical element each smr.category deploys (web/architecture/model/edge.c4)
EDGE_NODES = {"imu": "edge.imuNode", "camera": "edge.cameraNode"}


def c4str(s):
    return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"


def ident(s):
    return re.sub(r"[^a-z0-9-]+", "-", s.lower()).strip("-")


def read_env(path):
    env = {}
    for line in path.read_text().splitlines():
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$", line.strip())
        if m:
            env[m.group(1)] = m.group(2).strip().strip('"')
    return env


def interpolate(s, env):
    return re.sub(r"\$\{(\w+)(?::?-([^}]*))?\}", lambda m: env.get(m.group(1)) or m.group(2) or "", s)


def label_dict(labels):
    # Compose allows labels as a mapping or as a list of KEY=VALUE strings
    if isinstance(labels, list):
        return dict(item.split("=", 1) for item in labels)
    return labels or {}


def describe(name, labels, source):
    desc = (labels or {}).get("smr.description")
    if not desc:
        raise ValueError(f"{source}: service {name!r} has no smr.description label")
    return desc


def port(spec):
    # "${MQTT_PORT}:1883" -> "MQTT_PORT→1883", "9001:9001" -> "9001", "${X:-5050}:80" -> "5050→80"
    spec = str(spec)
    proto = ""
    if "/" in spec:
        spec, proto = spec.rsplit("/", 1)
        proto = "/" + proto
    host, _, container = spec.rpartition(":")
    host = re.sub(r"\$\{(\w+):-([^}]*)\}", r"\2", host)
    host = re.sub(r"\$\{(\w+)\}", r"\1", host)
    return (container if host in ("", container) else f"{host}→{container}") + proto


def compose_inventory():
    source = "docker-compose.yml"
    services = yaml.safe_load((ROOT / source).read_text())["services"]
    out = [HEADER.format(source=source), "model {", "  extend ams {"]
    for name, svc in services.items():
        built = svc.get("build")
        if built:
            dockerfile = built.get("dockerfile", "Dockerfile") if isinstance(built, dict) else "Dockerfile"
            context = built.get("context", ".") if isinstance(built, dict) else built
            tech = "built from " + str(Path(context) / dockerfile).removeprefix("./")
        else:
            tech = svc.get("image", "")
        ports = [port(p) for p in svc.get("ports") or []]
        if ports:
            tech += ", ports " + ", ".join(ports)
        profiles = svc.get("profiles") or []
        labels = label_dict(svc.get("labels"))
        out.append("")
        out.append(f"    {name} = {KINDS.get(name, 'service')} {c4str(name)} {{")
        if profiles:
            out.append("      #optional")
        out.append(f"      technology {c4str(tech)}")
        out.append(f"      description {c4str(describe(name, labels, source))}")
        out.append("      metadata {")
        out.append(f"        compose_service {c4str(name)}")
        if svc.get("container_name"):
            out.append(f"        container_name {c4str(svc['container_name'])}")
        for p in profiles:
            out.append(f"        compose_profile {c4str(p)}")
        for key in ("smr.monitor", "smr.autoheal"):
            if str(labels.get(key, "")).lower() == "true":
                out.append(f"        {key.split('.')[1]} 'true'")
        out.append("      }")
        out.append(f"      link {REPO_URL}/{source} {c4str(source)}")
        out.append("    }")
    out += ["  }", "}", ""]
    return "\n".join(out)


def edge_deployment():
    source = "deploy/swarm-edge-nodes.yml"
    env = read_env(ROOT / "deploy" / ".env.example")
    services = yaml.safe_load((ROOT / source).read_text())["services"]
    out = [
        HEADER.format(source=f"{source} (hostnames and ids from deploy/.env.example)"),
        "deployment {",
        "  swarm edgepis 'Edge Pis (Swarm workers)' {",
        "    description 'One Pi per edge service, placed by hostname or node label. Addresses are in the docs IP table.'",
    ]
    for name, svc in services.items():
        deploy = svc.get("deploy") or {}
        labels = label_dict(deploy.get("labels"))
        category = labels.get("smr.category")
        if category not in EDGE_NODES:
            raise ValueError(f"{source}: service {name!r} has smr.category {category!r}; "
                             f"add its node kind to EDGE_NODES in architecture/sync.py and web/architecture/model/edge.c4")
        constraint = interpolate(" ".join((deploy.get("placement") or {}).get("constraints") or []), env)
        m = re.search(r"node\.hostname == (\S+)", constraint)
        if m:
            host_id, host_title = ident(m.group(1)), m.group(1)
        else:
            m = re.search(r"node\.labels\.(\w+) == (\S+)", constraint)
            if not m:
                raise ValueError(f"{source}: service {name!r} has no hostname or node-label placement")
            host_id, host_title = ident(f"{m.group(1)}-{m.group(2)}-pi"), f"Pi with label {m.group(1)}={m.group(2)}"
        device = interpolate(str(labels.get("smr.device", "")), env)
        out.append("")
        out.append(f"    host {host_id} {c4str(host_title)} {{")
        out.append(f"      technology {c4str(f'edge_{name}, device {category}/{device}')}")
        out.append(f"      description {c4str('Placement: ' + constraint)}")
        out.append(f"      {name} = instanceOf {EDGE_NODES[category]} {{")
        out.append(f"        title {c4str(f'{name} ({category}/{device})')}")
        out.append(f"        description {c4str(describe(name, labels, source))}")
        out.append("      }")
        out.append("    }")
    out += ["  }", "}", ""]
    return "\n".join(out)


def render():
    """Generated file name -> content."""
    return {"inventory.c4": compose_inventory(), "edge-hosts.c4": edge_deployment()}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (OUT / name).write_text(text)
        print(f"wrote {(OUT / name).relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
